import AppKit
import CryptoKit
import ImageIO
import UniformTypeIdentifiers

/// What was read off the pasteboard at one change, before any processing.
struct CapturedClip: Sendable {
    var kind: ClipKind
    var text: String
    var content: ClipContent
    var isRich: Bool
    /// The raw image bytes (PNG, TIFF or JPEG) for image items.
    var imageData: Data?
}

enum PasteboardIO {
    /// Types written by password managers and other apps to say "do not keep this" (nspasteboard.org).
    static let concealedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
    ]

    private static let textTypes: [NSPasteboard.PasteboardType] = [.string, .rtf, .rtfd, .html]
    private static let richTypes: Set<NSPasteboard.PasteboardType> = [.rtf, .rtfd, .html]
    private static let imageTypes: [NSPasteboard.PasteboardType] =
        [.png, .tiff, NSPasteboard.PasteboardType(UTType.jpeg.identifier), NSPasteboard.PasteboardType(UTType.heic.identifier)]
    /// Marks content that arrived from another device through Universal Clipboard.
    static let remoteClipboardType = "com.apple.is-remote-clipboard"
    /// Larger content is not kept: it would bloat the history and slow every launch.
    static let maxBytes = 64 * 1024 * 1024

    /// Reads the pasteboard. Order: file references first (Finder and screenshot tools put a file plus
    /// an icon or pixels), then text, then image pixels.
    static func read(_ pasteboard: NSPasteboard, ignoreConcealed: Bool) -> CapturedClip? {
        let allTypes = Set((pasteboard.types ?? []).map(\.rawValue))
        if ignoreConcealed, !allTypes.isDisjoint(with: concealedTypes) { return nil }
        let items = pasteboard.pasteboardItems ?? []
        guard !items.isEmpty else { return nil }

        let fileURLs = items.compactMap { item -> URL? in
            guard let s = item.string(forType: .fileURL), let url = URL(string: s), url.isFileURL else { return nil }
            return url.standardizedFileURL
        }
        // Universal Clipboard file URLs point into Apple-managed temporary storage that other apps may
        // not be allowed to open later, so keep the pixels that come with them instead, or nothing.
        if !fileURLs.isEmpty, allTypes.contains(remoteClipboardType) {
            return readImage(pasteboard)
        }
        if !fileURLs.isEmpty {
            let reps = items.compactMap { item -> [TypedData]? in
                guard let data = item.data(forType: .fileURL) else { return nil }
                return [TypedData(type: NSPasteboard.PasteboardType.fileURL.rawValue, data: data)]
            }
            return CapturedClip(kind: .file, text: fileURLs.map(\.path).joined(separator: "\n"),
                                content: ClipContent(items: reps), isRich: false, imageData: nil)
        }

        if let string = pasteboard.string(forType: .string), !string.isEmpty {
            var total = 0
            var isRich = false
            let reps = items.map { item -> [TypedData] in
                textTypes.compactMap { type in
                    guard item.types.contains(type), let data = item.data(forType: type) else { return nil }
                    total += data.count
                    guard total <= maxBytes else { return nil }
                    if richTypes.contains(type) { isRich = true }
                    return TypedData(type: type.rawValue, data: data)
                }
            }.filter { !$0.isEmpty }
            guard string.utf8.count <= maxBytes else { return nil }
            return CapturedClip(kind: .text, text: string, content: ClipContent(items: reps), isRich: isRich, imageData: nil)
        }

        return readImage(pasteboard)
    }

    private static func readImage(_ pasteboard: NSPasteboard) -> CapturedClip? {
        for type in imageTypes {
            if let data = pasteboard.data(forType: type), data.count <= maxBytes {
                return CapturedClip(kind: .image, text: "", content: ClipContent(items: []), isRich: false, imageData: data)
            }
        }
        return nil
    }

    /// Puts an item back exactly as it was captured. Images also get a TIFF for apps that only read that.
    static func write(_ content: ClipContent, kind: ClipKind, to pasteboard: NSPasteboard) {
        pasteboard.clearContents()
        let objects: [NSPasteboardItem] = content.items.map { reps in
            let item = NSPasteboardItem()
            for rep in reps { item.setData(rep.data, forType: NSPasteboard.PasteboardType(rep.type)) }
            if kind == .image, let png = reps.first(where: { $0.type == NSPasteboard.PasteboardType.png.rawValue })?.data,
               let tiff = NSBitmapImageRep(data: png)?.tiffRepresentation {
                item.setData(tiff, forType: .tiff)
            }
            return item
        }
        pasteboard.writeObjects(objects)
    }

    static func writePlainText(_ text: String, to pasteboard: NSPasteboard) {
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
    }
}

/// Off-main processing of a captured clip: hashing, image conversion and the list thumbnail.
enum ClipProcessing {
    struct Result: Sendable {
        var hash: String
        var content: ClipContent
        var thumbnail: Data?
        var width: Int?
        var height: Int?
    }

    static func process(_ clip: CapturedClip) -> Result? {
        switch clip.kind {
        case .text, .file:
            var thumbnail: Data?
            if clip.kind == .file, clip.text.split(separator: "\n").count == 1,
               let source = CGImageSourceCreateWithURL(URL(fileURLWithPath: clip.text) as CFURL, nil),
               CGImageSourceGetCount(source) > 0 {
                thumbnail = makeThumbnail(source)
            }
            return Result(hash: sha256(Data(clip.text.utf8)), content: clip.content, thumbnail: thumbnail)
        case .image:
            guard let data = clip.imageData,
                  let source = CGImageSourceCreateWithData(data as CFData, nil),
                  CGImageSourceGetCount(source) > 0 else { return nil }
            let props = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any]
            let width = props?[kCGImagePropertyPixelWidth] as? Int
            let height = props?[kCGImagePropertyPixelHeight] as? Int
            // Keep PNG as is; convert TIFF (often uncompressed) and JPEG to PNG once, here.
            let png: Data
            if (CGImageSourceGetType(source) as String?) == UTType.png.identifier {
                png = data
            } else if let converted = encode(source, as: UTType.png) {
                png = converted
            } else {
                return nil
            }
            let reps = [TypedData(type: NSPasteboard.PasteboardType.png.rawValue, data: png)]
            return Result(hash: sha256(data), content: ClipContent(items: [reps]),
                          thumbnail: makeThumbnail(source), width: width, height: height)
        }
    }

    static func sha256(_ data: Data) -> String {
        SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
    }

    /// 2x the 48 pt list thumbnail, as JPEG.
    private static func makeThumbnail(_ source: CGImageSource) -> Data? {
        let options: [CFString: Any] = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceCreateThumbnailWithTransform: true,
            kCGImageSourceThumbnailMaxPixelSize: 160,
        ]
        guard let image = CGImageSourceCreateThumbnailAtIndex(source, 0, options as CFDictionary) else { return nil }
        let out = NSMutableData()
        guard let dest = CGImageDestinationCreateWithData(out, UTType.jpeg.identifier as CFString, 1, nil) else { return nil }
        // JPEG has no alpha; flatten transparent pixels onto white rather than black.
        let flattened = flatten(image) ?? image
        CGImageDestinationAddImage(dest, flattened, [kCGImageDestinationLossyCompressionQuality: 0.8] as CFDictionary)
        return CGImageDestinationFinalize(dest) ? out as Data : nil
    }

    private static func flatten(_ image: CGImage) -> CGImage? {
        guard let ctx = CGContext(data: nil, width: image.width, height: image.height, bitsPerComponent: 8, bytesPerRow: 0,
                                  space: CGColorSpaceCreateDeviceRGB(), bitmapInfo: CGImageAlphaInfo.noneSkipLast.rawValue) else { return nil }
        let rect = CGRect(x: 0, y: 0, width: image.width, height: image.height)
        ctx.setFillColor(CGColor(gray: 1, alpha: 1))
        ctx.fill(rect)
        ctx.draw(image, in: rect)
        return ctx.makeImage()
    }

    private static func encode(_ source: CGImageSource, as type: UTType) -> Data? {
        guard let image = CGImageSourceCreateImageAtIndex(source, 0, nil) else { return nil }
        let out = NSMutableData()
        guard let dest = CGImageDestinationCreateWithData(out, type.identifier as CFString, 1, nil) else { return nil }
        CGImageDestinationAddImage(dest, image, nil)
        return CGImageDestinationFinalize(dest) ? out as Data : nil
    }
}
